SELECT TOP (50)
    wait_type,
    waiting_tasks_count,
    CONVERT(decimal(19, 2), wait_time_ms / 1000.0) AS wait_time_seconds,
    CONVERT(decimal(19, 2), signal_wait_time_ms / 1000.0) AS signal_wait_seconds,
    CONVERT(decimal(9, 2), 100.0 * wait_time_ms / NULLIF(SUM(wait_time_ms) OVER (), 0)) AS wait_time_percent,
    max_wait_time_ms
FROM sys.dm_os_wait_stats
WHERE wait_time_ms > 0
    AND wait_type NOT IN (
        'BROKER_EVENTHANDLER', 'BROKER_RECEIVE_WAITFOR', 'BROKER_TASK_STOP',
        'BROKER_TO_FLUSH', 'BROKER_TRANSMITTER', 'CHECKPOINT_QUEUE',
        'CHKPT', 'CLR_AUTO_EVENT', 'CLR_MANUAL_EVENT', 'CLR_SEMAPHORE',
        'DBMIRROR_EVENTS_QUEUE', 'DIRTY_PAGE_POLL', 'DISPATCHER_QUEUE_SEMAPHORE',
        'EXECSYNC', 'FT_IFTS_SCHEDULER_IDLE_WAIT', 'HADR_CLUSAPI_CALL',
        'HADR_FILESTREAM_IOMGR_IOCOMPLETION', 'HADR_LOGCAPTURE_WAIT',
        'HADR_NOTIFICATION_DEQUEUE', 'HADR_TIMER_TASK', 'HADR_WORK_QUEUE',
        'KSOURCE_WAKEUP', 'LAZYWRITER_SLEEP', 'LOGMGR_QUEUE', 'ONDEMAND_TASK_QUEUE',
        'REQUEST_FOR_DEADLOCK_SEARCH', 'RESOURCE_QUEUE', 'SERVER_IDLE_CHECK',
        'SLEEP_BPOOL_FLUSH', 'SLEEP_DBSTARTUP', 'SLEEP_TASK', 'SLEEP_TEMPDBSTARTUP',
        'SQLTRACE_BUFFER_FLUSH', 'WAITFOR', 'WAITFOR_TASKSHUTDOWN',
        'WAIT_XTP_HOST_WAIT', 'WAIT_XTP_OFFLINE_CKPT_NEW_LOG', 'XE_DISPATCHER_WAIT',
        'XE_TIMER_EVENT'
    )
ORDER BY wait_time_ms DESC;
